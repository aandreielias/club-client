// Copies the server's contract snapshots (club-server/docs/api) into src/lib/api and generates TypeScript types from the
// OpenAPI document. Run after the server's ApiContractIT/ErrorCodesTest rewrote them: npm run api:sync
// openapi-typescript runs through npx with its own TypeScript 5 (it does not accept the project's TypeScript 6 as peer).
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const from = new URL('../../club-server/docs/api/', import.meta.url);
const to = new URL('../src/lib/api/', import.meta.url);
copyFileSync(new URL('error-codes.json', from), new URL('error-codes.json', to));
const schema = fileURLToPath(new URL('schema.d.ts', to));
execFileSync(
  'npx',
  [
    '-y',
    '-p',
    'openapi-typescript@7.13.0',
    '-p',
    'typescript@5.9.3',
    'openapi-typescript',
    fileURLToPath(new URL('openapi.json', from)),
    '-o',
    schema,
  ],
  { stdio: 'inherit' },
);
writeFileSync(schema, '// Generated by scripts/sync-api.mjs from club-server/docs/api/openapi.json; do not edit.\n' + readFileSync(schema, 'utf8'));
